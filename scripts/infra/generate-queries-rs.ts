/** Render the entity's typed ordering clause, so a read cannot be ordered by another table's column. */
function renderOrderStruct(entity: string): string[] {
    const order = `${entity}Order`;
    return [
        `/// One ordering clause of a \`${entity}\` read, built from \`${entity}OrderField\`.`,
        "#[derive(Clone, Debug, PartialEq)]",
        `pub struct ${order} {`,
        `    field: ${entity}OrderField,`,
        "    direction: SortDirection,",
        "    nulls: Option<NullsOrder>,",
        "}",
        "",
        `impl ${order} {`,
        "    /// Order nulls before values.",
        "    #[must_use]",
        "    pub fn nulls_first(mut self) -> Self {",
        "        self.nulls = Some(NullsOrder::First);",
        "        self",
        "    }",
        "",
        "    /// Order nulls after values.",
        "    #[must_use]",
        "    pub fn nulls_last(mut self) -> Self {",
        "        self.nulls = Some(NullsOrder::Last);",
        "        self",
        "    }",
        "",
        "    /// The builder's ordering clause.",
        "    #[must_use]",
        "    pub fn into_sort(self) -> Sort {",
        "        Sort {",
        "            column: self.field.as_str().to_owned(),",
        "            direction: self.direction,",
        "            nulls: self.nulls,",
        "        }",
        "    }",
        "}",
    ];
}

/** The `with_select` signature, wrapped when the entity's name makes it too long for one line. */
function withSelectSignature(select: string): string[] {
    const oneLine = `    pub fn with_select(fields: impl IntoIterator<Item = ${select}>) -> Self {`;
    return oneLine.length > MAX_LINE_WIDTH
        ? ["    pub fn with_select(", `        fields: impl IntoIterator<Item = ${select}>,`, "    ) -> Self {"]
        : [oneLine];
}

/** Render the entity's read options, whose fields are the entity's own typed sets. */
function renderReadOptions(entity: string): string[] {
    const options = `${entity}ReadOptions`;
    const select = `${entity}SelectField`;
    const order = `${entity}Order`;
    return [
        `/// What a read of \`${entity}\` selects, filters, orders, and pages.`,
        "#[derive(Clone, Debug, Default)]",
        `pub struct ${options} {`,
        "    /// The selected columns; empty selects every column.",
        `    pub select: Vec<${select}>,`,
        `    /// The filters, combined with \`and\`; each is built by a \`${entity}FilterField\` helper.`,
        `    pub filters: Vec<${entity}Filter>,`,
        "    /// The ordering clauses, in order.",
        `    pub order: Vec<${order}>,`,
        "    /// The maximum number of rows.",
        "    pub limit: Option<u64>,",
        "    /// The number of leading rows to skip.",
        "    pub offset: Option<u64>,",
        "}",
        "",
        `impl ${options} {`,
        "    /// A read that selects `fields`.",
        "    #[must_use]",
        ...withSelectSignature(select),
        "        Self {",
        "            select: fields.into_iter().collect(),",
        "            ..Self::default()",
        "        }",
        "    }",
        "",
        `    /// Add a filter, built by a \`${entity}FilterField\` helper.`,
        "    #[must_use]",
        `    pub fn filter(mut self, filter: ${entity}Filter) -> Self {`,
        "        self.filters.push(filter);",
        "        self",
        "    }",
        "",
        `    /// Add an ordering clause, built by a \`${entity}OrderField\` helper.`,
        "    #[must_use]",
        `    pub fn order(mut self, order: ${order}) -> Self {`,
        "        self.order.push(order);",
        "        self",
        "    }",
        "",
        "    /// Keep at most `limit` rows.",
        "    #[must_use]",
        "    pub fn limit(mut self, limit: u64) -> Self {",
        "        self.limit = Some(limit);",
        "        self",
        "    }",
        "",
        "    /// Skip `offset` leading rows.",
        "    #[must_use]",
        "    pub fn offset(mut self, offset: u64) -> Self {",
        "        self.offset = Some(offset);",
        "        self",
        "    }",
        "",
        "    /// The source-independent read the crate's planner takes; not part of the public surface.",
        "    #[must_use]",
        "    pub(crate) fn into_read_options(self) -> ReadOptions {",
        "        ReadOptions {",
        "            columns: self",
        "                .select",
        "                .into_iter()",
        "                .map(|field| field.select())",
        "                .collect(),",
        "            filters: self",
        "                .filters",
        "                .into_iter()",
        "                .map(|filter| filter.into_typed_filter())",
        "                .collect(),",
        "            sort: self",
        "                .order",
        "                .into_iter()",
        "                .map(|order| order.into_sort())",
        "                .collect(),",
        "            limit: self.limit,",
        "            offset: self.offset,",
        "        }",
        "    }",
        "}",
    ];
}

/** Render one entity's query: its typed fields, its typed read options, and the read itself. */
export function renderQueryModule(table: Table, spec?: SpecModel): string {
    const entity = table.interfaceName;
    const query = queryFunctionName(entity);
    const options = `${entity}ReadOptions`;
    const lines: string[] = [HEADER, ""];
    lines.push("use std::borrow::Borrow;");
    lines.push("");
    lines.push("use crate::db::{");
    lines.push("    BindValue, PlannedQuery, ReadError, ReadOptions, SqlExecutor, SqlType, TypedFilter, decode_rows,");
    lines.push("};");
    lines.push("use datagrid_query::{");
    lines.push("    Combinator, FilterOperator, NullsOrder, SelectColumn, Sort, SortDirection, Value,");
    lines.push("};");
    const filters = filterFields(table, spec);
    const modelImports = new Set([`use ${selectTypePath(table)};`, ...filters.flatMap((field) => field.imports)]);
    for (const importLine of [...modelImports].sort()) {
        lines.push(importLine);
    }
    lines.push("");
    lines.push(`/// A column of \`${entity}\` a read may select.`);
    lines.push(fieldEnumDerive());
    const selectable: FieldInfo[] = selectableFields(table).map((name) => ({ name }));
    lines.push(...renderFieldEnum(entity, "Select", selectable, selectHelper()));
    lines.push("");
    lines.push(`/// A column of \`${entity}\` a read may filter on, from \`@queryFilter\`.`);
    lines.push(fieldEnumDerive());
    lines.push(...renderFieldEnum(entity, "Filter", filters, []));
    lines.push("");
    lines.push(...renderFilterBuilders(entity, filters));
    lines.push("");
    lines.push(...renderFilterStruct(entity));
    lines.push("");
    lines.push(`/// A column of \`${entity}\` a read may order by, from \`@queryOrderBy\`.`);
    lines.push(fieldEnumDerive());
    const orderable: FieldInfo[] = orderFields(table).map((name) => ({ name }));
    lines.push(...renderFieldEnum(entity, "Order", orderable, orderHelpers(entity)));
    lines.push("");
    lines.push(...renderOrderStruct(entity));
    lines.push("");
    lines.push(...renderReadOptions(entity));
    lines.push("");
    lines.push(`/// Build the read for \`${entity}\` over \`${table.name}\`.`);
    lines.push("///");
    lines.push("/// # Errors");
    lines.push("///");
    lines.push("/// Returns [`ReadError::Build`] when the options do not form a valid statement.");
    const signature = `pub fn build_${query}(options: ${options}) -> Result<PlannedQuery, ReadError> {`;
    if (signature.length > MAX_LINE_WIDTH) {
        lines.push(`pub fn build_${query}(`);
        lines.push(`    options: ${options},`);
        lines.push(") -> Result<PlannedQuery, ReadError> {");
    } else {
        lines.push(signature);
    }
    lines.push("    let read = options.into_read_options();");
    lines.push(`    read.plan(${JSON.stringify(table.name)}, None)`);
    lines.push("}");
    lines.push("");
    lines.push(`/// Read \`${entity}\` rows, decoded into \`${entity}Select\`.`);
    lines.push("///");
    lines.push("/// # Errors");
    lines.push("///");
    lines.push("/// Returns [`ReadError`] when the statement cannot be built, run, or decoded.");
    lines.push(`pub async fn ${query}(`);
    lines.push("    db: &impl SqlExecutor,");
    lines.push(`    options: ${options},`);
    lines.push(`) -> Result<Vec<${entity}Select>, ReadError> {`);
    lines.push(`    let query = build_${query}(options)?;`);
    lines.push("    let rows = db.query(&query.sql, &query.params).await?;");
    lines.push("    decode_rows(rows)");
    lines.push("}");
    return lines.join("\n") + "\n";
}

/** Render every generated file, keyed by file name (including the barrel). */
export function generateQueryModules(tables: Map<string, Table>, spec?: SpecModel): Map<string, string> {
    const entities = [...tables.values()]
        .filter((table) => table.queries.includes("query"))
        .sort((a, b) => a.interfaceName.localeCompare(b.interfaceName));

    const files = new Map<string, string>();
    const lines: string[] = [HEADER, ""];
    for (const table of entities) {
        const module = queryFunctionName(table.interfaceName);
        files.set(`${module}.rs`, renderQueryModule(table, spec));
        lines.push(`mod ${module};`);
    }
    if (entities.length > 0) {
        lines.push("");
    }
    for (const table of entities) {
        lines.push(`pub use ${queryFunctionName(table.interfaceName)}::*;`);
    }
    files.set(MODULE_FILE, lines.join("\n") + "\n");
    return files;
}

/** Remove the generated modules the spec no longer declares, so an entity that drops a read leaves no file. */
function pruneStale(outDir: string, keep: Set<string>): void {
    for (const entry of readdirSync(outDir, { withFileTypes: true })) {
        if (!entry.isFile() || !entry.name.startsWith("query_") || !entry.name.endsWith(".rs") || keep.has(entry.name)) {
            continue;
        }
        const file = join(outDir, entry.name);
        if (readFileSync(file, "utf8").split("\n", 1)[0] === HEADER) {
            rmSync(file);
        }
    }
}

/** Write the query modules for a parsed spec and return the exit code. */
export function run(spec: SpecModel, argv: readonly string[] = process.argv, output: Output = console): number {
    const { tables, diagnostics } = buildSpecTables(spec);

    for (const diagnostic of diagnostics) {
        output.error(`${diagnostic.filePath}:${diagnostic.line}: ${diagnostic.message}`);
    }
    if (diagnostics.length > 0) {
        return 1;
    }

    const outIndex = argv.indexOf("--out");
    const outDir = outIndex === -1 ? DEFAULT_OUT_DIR : argv[outIndex + 1];
    if (!outDir) {
        output.error("--out needs a directory");
        return 1;
    }

    const files = generateQueryModules(tables, spec);
    mkdirSync(outDir, { recursive: true });
    for (const [name, content] of files) {
        writeFileSync(join(outDir, name), content);
    }
    pruneStale(outDir, new Set(files.keys()));
    output.log(`wrote ${files.size} Rust query file(s) to ${outDir}`);
    return 0;
}

if (import.meta.main) {
    process.exitCode = run(loadSpec());
}
