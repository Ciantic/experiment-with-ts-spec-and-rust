/** Generate the Rust per-entity query builders into the infra crate. See docs/rust-queries.md. */
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { INFRA_CRATE_ROOT } from "../paths.ts";
import { rustModelItemPath, rustValueType, snakeName, variantIdentifier } from "../models-rs/generate-models.ts";
import { loadSpec, type QueryOperator, type SpecModel } from "../spec/spec-model.ts";
import { buildSpecTables, type Table } from "./postgres-model.ts";

/** The channels a run reports on: the console, or a caller's own sink. */
type Output = Pick<Console, "log" | "error">;

/** Where the generated modules are written when no `--out` is given. */
const DEFAULT_OUT_DIR = join(INFRA_CRATE_ROOT, "src/db/queries");

const HEADER = "// Generated by scripts/infra/generate-queries-rs.ts. Do not edit.";

/** The line width the generated files stay under. */
const MAX_LINE_WIDTH = 100;

/** The Rust `SqlType` variant of each Postgres type, keyed by the name the table model carries. */
const SQL_TYPES: Readonly<Record<string, string>> = {
    boolean: "Bool",
    bool: "Bool",
    int2: "I16",
    smallint: "I16",
    int4: "I32",
    integer: "I32",
    int8: "I64",
    bigint: "I64",
    float4: "F32",
    real: "F32",
    float8: "F64",
    "double precision": "F64",
    decimal: "Decimal",
    numeric: "Decimal",
    money: "Decimal",
    text: "Text",
    varchar: "Text",
    "character varying": "Text",
    char: "Text",
    character: "Text",
    uuid: "Uuid",
    timestamptz: "Timestamptz",
    "timestamp with time zone": "Timestamptz",
    timestamp: "Timestamp",
    "timestamp without time zone": "Timestamp",
    date: "Date",
    time: "Time",
    json: "Json",
    jsonb: "Json",
    bytea: "Bytea",
};

/** The `SqlType` variant for a column, so an unlisted textual type still binds as text. */
export function sqlTypeVariant(sqlType: string): string {
    return SQL_TYPES[sqlType] ?? "Text";
}

/** The barrel re-exporting every generated query module. */
const MODULE_FILE = "mod.rs";

/** The module and function name for an entity, e.g. `Invoice` -> `query_invoice`. */
export function queryFunctionName(entity: string): string {
    return `query_${snakeName(entity)}`;
}

/** The module file for an entity's read, e.g. `Invoice` -> `query_invoice.rs`. */
export function queryFileName(entity: string): string {
    return `${queryFunctionName(entity)}.rs`;
}

/** The selected type a read decodes into, e.g. `models::domain::invoicing_service::invoice::InvoiceSelect`. */
export function selectTypePath(table: Table): string {
    return rustModelItemPath(table.importSpecifier, `${table.interfaceName}Select`);
}

/** The columns `@inlined` branches reach through their branch, so a read does not select them by name. */
function inlinedColumns(table: Table): Set<string> {
    const columns = new Set<string>();
    for (const relation of table.relations.values()) {
        if (relation.kind === "inlined") {
            for (const column of Object.values(relation.columns ?? {})) {
                columns.add(column);
            }
        }
    }
    return columns;
}

/** The columns an entity's read may select: every physical column a branch does not own. */
export function selectableFields(table: Table): string[] {
    const inlined = inlinedColumns(table);
    return table.columns.map((column) => column.name).filter((name) => !inlined.has(name));
}

/** A filter field: its column, the Postgres type it binds as, the comparisons it permits, and a value's Rust type. */
export interface FilterFieldInfo {
    name: string;
    sqlType: string;
    /** The model's Rust type for this column; `Value` when the spec shape has no Rust equivalent. */
    valueType: string;
    /** The comparisons the column's `@queryFilter ops=` whitelists, in canonical order. */
    operators: QueryOperator[];
    /** `use` statements for a value type declared in another model module. */
    imports: string[];
}

/** The fields an entity exposes as filters, with the comparisons and model type each takes. */
export function filterFields(table: Table, spec?: SpecModel): FilterFieldInfo[] {
    return table.columns
        .filter((column) => column.queryFilter !== undefined)
        .map((column) => ({
            ...describeColumn(table, column, spec),
            operators: column.queryFilter?.ops ?? [],
        }));
}

/** A column as a filter field: its name, Postgres type, and the model type of a value it compares. */
function describeColumn(
    table: Table,
    column: Table["columns"][number],
    spec?: SpecModel,
): Omit<FilterFieldInfo, "operators"> {
    const entity = spec?.interfaces.get(table.interfaceName);
    const property = entity?.properties.find((candidate) => candidate.name === column.name);
    const resolved = property === undefined || spec === undefined ? undefined : rustValueType(spec, property);
    return {
        name: column.name,
        sqlType: sqlTypeVariant(column.sqlType),
        valueType: resolved?.type ?? "Value",
        imports: resolved?.imports ?? [],
    };
}

/** The field names an entity exposes as ordering keys: its `@queryOrderBy` scalar columns. */
export function orderFields(table: Table): string[] {
    return table.columns.filter((column) => column.queryOrder !== undefined).map((column) => column.name);
}

/** The enum name of one field set, e.g. `Invoice` + `Select` -> `InvoiceSelectField`. */
export function fieldEnumName(entity: string, kind: "Select" | "Order"): string {
    return `${entity}${kind}Field`;
}

/** The variant for a field, e.g. `tenantId` -> `TenantId`. */
function fieldVariant(field: string): string {
    return variantIdentifier(field);
}

/** A field of an enum, with the Postgres type it binds as when it is a filter. */
export interface FieldInfo {
    name: string;
    sqlType?: string;
}

/** Render an enum of one entity's fields: the columns it names, plus the helpers the caller builds with. */
function renderFieldEnum(entity: string, kind: "Select" | "Order", fields: FieldInfo[], helpers: string[]): string[] {
    const name = fieldEnumName(entity, kind);
    const lines: string[] = fields.length === 0 ? [`pub enum ${name} {}`] : [`pub enum ${name} {`];
    for (const field of fields) {
        lines.push(`    #[serde(rename = ${JSON.stringify(field.name)})]`);
        lines.push(`    ${fieldVariant(field.name)},`);
    }
    if (fields.length > 0) {
        lines.push("}");
    }
    lines.push("");
    lines.push(`impl ${name} {`);
    if (fields.length === 0) {
        lines.push("    /// Every field; empty because the entity declares none.");
        lines.push("    pub const ALL: &'static [Self] = &[];");
        lines.push("");
        lines.push("    /// The column this field names.");
        lines.push("    #[must_use]");
        lines.push("    pub const fn as_str(self) -> &'static str {");
        lines.push("        match self {}");
        lines.push("    }");
    } else {
        lines.push("    /// Every field, in declaration order.");
        lines.push("    #[rustfmt::skip]");
        lines.push("    pub const ALL: &'static [Self] = &[");
        for (const field of fields) {
            lines.push(`        Self::${fieldVariant(field.name)},`);
        }
        lines.push("    ];");
        lines.push("");
        lines.push("    /// The column this field names.");
        lines.push("    #[must_use]");
        lines.push("    pub const fn as_str(self) -> &'static str {");
        lines.push("        match self {");
        for (const field of fields) {
            lines.push(`            Self::${fieldVariant(field.name)} => ${JSON.stringify(field.name)},`);
        }
        lines.push("        }");
        lines.push("    }");
    }
    if (helpers.length > 0) {
        lines.push("");
        for (const helper of helpers) {
            lines.push(helper.length === 0 ? helper : `    ${helper}`);
        }
    }
    lines.push("}");
    lines.push("");
    lines.push(`impl std::fmt::Display for ${name} {`);
    lines.push("    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {");
    lines.push("        f.write_str(self.as_str())");
    lines.push("    }");
    lines.push("}");
    return lines;
}

/** The derive line above a field enum. */
function fieldEnumDerive(): string[] {
    return [
        "#[derive(",
        "    Clone, Copy, Debug, serde::Deserialize, Eq, Hash, Ord, PartialEq, PartialOrd, serde::Serialize,",
        ")]",
    ];
}

/** The `select` helpers of a selectable field: the planner's entry, and the wire name's lookup. */
function selectHelper(): string[] {
    return [
        "/// The select-list entry for this column.",
        "#[must_use]",
        "pub fn select(self) -> SelectColumn {",
        "    SelectColumn::Name(self.as_str().to_owned())",
        "}",
        "",
        "/// The field a wire column names; `None` when the entity has no such column.",
        "#[must_use]",
        "pub fn from_column(column: &str) -> Option<Self> {",
        "    Self::ALL",
        "        .iter()",
        "        .copied()",
        "        .find(|field| field.as_str() == column)",
        "}",
    ];
}

/** The `selection` call as rustfmt writes it: one line while it fits, else the `map` on its own line. */
function selectionCall(field: string): string[] {
    const oneLine = `        flat_filter::selection(deserializer, ${field}::from_column).map(Self)`;
    return oneLine.length <= MAX_LINE_WIDTH
        ? [oneLine]
        : [
              `        flat_filter::selection(deserializer, ${field}::from_column)`,
              "            .map(Self)",
          ];
}

/** Render the selection a read carries: on the wire, an object naming each selected column. */
function renderSelectStruct(entity: string): string[] {
    const select = `${entity}Selection`;
    const field = `${entity}SelectField`;
    return [
        `/// The columns a \`${entity}\` read selects; empty selects every one.`,
        "///",
        "/// On the wire it is an object naming each column, as the TypeScript read sends it.",
        "#[derive(Clone, Debug, Default, PartialEq)]",
        `pub struct ${select}(pub Vec<${field}>);`,
        "",
        `impl serde::Serialize for ${select} {`,
        "    fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {",
        "        let mut map = serializer.serialize_map(Some(self.0.len()))?;",
        "        for field in &self.0 {",
        "            map.serialize_entry(field.as_str(), &true)?;",
        "        }",
        "        map.end()",
        "    }",
        "}",
        "",
        `impl<'de> serde::Deserialize<'de> for ${select} {`,
        "    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {",
        ...selectionCall(field),
        "    }",
        "}",
        "",
        `impl FromIterator<${field}> for ${select} {`,
        `    fn from_iter<I: IntoIterator<Item = ${field}>>(fields: I) -> Self {`,
        "        Self(fields.into_iter().collect())",
        "    }",
        "}",
    ];
}

/** Render the entity's filters as one `flat_query_filters!` invocation, which writes them all. */
export function renderFilters(entity: string, fields: FilterFieldInfo[]): string[] {
    const lines = ["flat_query_filters! {", `    ${entity} {`];
    for (const field of fields) {
        lines.push(`        ${field.name}: ${field.valueType}, ${field.sqlType}, [${field.operators.join(", ")}],`);
    }
    lines.push("    }", "}");
    return lines;
}

/** The ordering helpers of an orderable field. */
function orderHelpers(entity: string): string[] {
    const order = `${entity}Order`;
    return [
        "/// Ascending order on this column.",
        "#[must_use]",
        `pub fn asc(self) -> ${order} {`,
        `    ${order} {`,
        "        field: self,",
        "        direction: SortDirection::Asc,",
        "    }",
        "}",
        "",
        "/// Descending order on this column.",
        "#[must_use]",
        `pub fn desc(self) -> ${order} {`,
        `    ${order} {`,
        "        field: self,",
        "        direction: SortDirection::Desc,",
        "    }",
        "}",
        "",
        "/// The field a wire column names; `None` when the entity has no such column.",
        "#[must_use]",
        "pub fn from_column(column: &str) -> Option<Self> {",
        "    Self::ALL",
        "        .iter()",
        "        .copied()",
        "        .find(|field| field.as_str() == column)",
        "}",
    ];
}

/** The `sort` call as rustfmt writes it: one line while it fits, else after the `=`. */
function sortCall(entity: string): string[] {
    const oneLine = `        let (field, direction) = flat_filter::sort(deserializer, ${entity}OrderField::from_column)?;`;
    return oneLine.length <= MAX_LINE_WIDTH
        ? [oneLine]
        : [
              "        let (field, direction) =",
              `            flat_filter::sort(deserializer, ${entity}OrderField::from_column)?;`,
          ];
}

/** Render the entity's typed ordering clause, so a read cannot be ordered by another table's column. */
function renderOrderStruct(entity: string): string[] {
    const order = `${entity}Order`;
    return [
        `/// One ordering clause of a \`${entity}\` read, built from \`${entity}OrderField\`.`,
        "///",
        `/// On the wire it is a \`["column", "asc" | "desc"]\` tuple, as the TypeScript read sends it.`,
        "#[derive(Clone, Debug, PartialEq)]",
        `pub struct ${order} {`,
        `    field: ${entity}OrderField,`,
        "    direction: SortDirection,",
        "}",
        "",
        `impl serde::Serialize for ${order} {`,
        "    fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {",
        "        let mut tuple = serializer.serialize_tuple(2)?;",
        "        tuple.serialize_element(self.field.as_str())?;",
        "        tuple.serialize_element(&self.direction)?;",
        "        tuple.end()",
        "    }",
        "}",
        "",
        `impl<'de> serde::Deserialize<'de> for ${order} {`,
        "    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {",
        ...sortCall(entity),
        "        Ok(Self { field, direction })",
        "    }",
        "}",
        "",
        `impl ${order} {`,
        "    /// The builder's ordering clause.",
        "    #[must_use]",
        "    pub fn into_sort(self) -> Sort {",
        "        Sort {",
        "            column: self.field.as_str().to_owned(),",
        "            direction: self.direction,",
        "            nulls: None,",
        "        }",
        "    }",
        "}",
    ];
}

/** A `use` statement as rustfmt lays it out: items filled to the line width, each line indented, trailing commas. */
function useList(path: string, items: string[]): string[] {
    const filled: string[] = [];
    let line = "";
    for (const item of items) {
        const piece = `${item},`;
        if (line !== "" && 4 + line.length + 1 + piece.length > MAX_LINE_WIDTH) {
            filled.push(line);
            line = piece;
            continue;
        }
        line = line === "" ? piece : `${line} ${piece}`;
    }
    filled.push(line);
    if (filled.length === 1 && `use ${path}::{${filled[0]}};`.length <= MAX_LINE_WIDTH) {
        return [`use ${path}::{${filled[0]}};`];
    }
    return [`use ${path}::{`, ...filled.map((entry) => `    ${entry}`), "};"];
}

/** Render the entity's query type, plus how the entity lowers to the shared builder's read. */
function renderReadEntity(entity: string, table: string): string[] {
    const builder = `${entity}Query`;
    return [
        `/// The query of \`${entity}\`: its selection, filters, ordering, and paging.`,
        `pub type ${builder} = EntityQuery<${entity}>;`,
        "",
        `impl ReadEntity for ${entity} {`,
        `    type Select = ${entity}Select;`,
        `    type SelectField = ${entity}SelectField;`,
        `    type Selection = ${entity}Selection;`,
        `    type Filter = ${entity}Filter;`,
        `    type Order = ${entity}Order;`,
        "",
        `    const TABLE: &'static str = ${JSON.stringify(table)};`,
        "",
        "    fn group(kind: FilterKind, filters: Vec<Self::Filter>) -> Self::Filter {",
        `        ${entity}Filter::Group { kind, filters }`,
        "    }",
        "",
        "    fn lower(",
        "        select: Self::Selection,",
        "        filters: Vec<Self::Filter>,",
        "        order: Vec<Self::Order>,",
        "        limit: Option<u64>,",
        "        offset: Option<u64>,",
        "    ) -> Result<LoweredRead, ReadError> {",
        "        let mut typed = Vec::new();",
        "        for filter in filters {",
        "            typed.extend(filter.into_typed_filters()?);",
        "        }",
        "        Ok(LoweredRead(ReadOptions {",
        "            columns: select.0.into_iter().map(|field| field.select()).collect(),",
        "            filters: typed,",
        "            sort: order.into_iter().map(|clause| clause.into_sort()).collect(),",
        "            limit,",
        "            offset,",
        "        }))",
        "    }",
        "}",
    ];
}

/** Render one entity's query module: its typed fields, and its query over the shared builder. */
export function renderQueryModule(table: Table, spec?: SpecModel): string {
    const entity = table.interfaceName;
    const lines: string[] = [HEADER, ""];
    lines.push(
        ...useList(
            "crate::db",
            ["EntityQuery", "FilterKind", "LoweredRead", "ReadEntity", "ReadError", "ReadOptions", "SqlType", "TypedFilter", "flat_filter"].sort(),
        ),
    );
    const filters = filterFields(table, spec);
    // No `Combinator`: a group's kind lowers through `FilterKind::combinator`.
    const builderImports = ["SelectColumn", "Sort", "SortDirection"];
    // Only a lowering names the builder's operator; an entity with no filter has none to name.
    if (filters.length > 0) {
        builderImports.push("FilterOperator");
    }
    builderImports.sort();
    lines.push(`use datagrid_query::{${builderImports.join(", ")}};`);
    lines.push("use macro_helpers::flat_query_filters;");
    // Every module writes one ordering clause and implements the read trait for its model type.
    const modelImports = new Set([
        `use ${rustModelItemPath(table.importSpecifier, entity)};`,
        `use ${selectTypePath(table)};`,
        ...filters.flatMap((field) => field.imports),
    ]);
    for (const importLine of [...modelImports].sort()) {
        lines.push(importLine);
    }
    lines.push("use serde::ser::{SerializeMap, SerializeTuple};");
    lines.push("");
    lines.push(`/// A column of \`${entity}\` a read may select.`);
    lines.push(...fieldEnumDerive());
    const selectable: FieldInfo[] = selectableFields(table).map((name) => ({ name }));
    lines.push(...renderFieldEnum(entity, "Select", selectable, selectHelper()));
    lines.push("");
    lines.push(...renderSelectStruct(entity));
    lines.push("");
    lines.push(...renderFilters(entity, filters));
    lines.push("");
    lines.push(`/// A column of \`${entity}\` a read may order by, from \`@queryOrderBy\`.`);
    lines.push(...fieldEnumDerive());
    const orderable: FieldInfo[] = orderFields(table).map((name) => ({ name }));
    lines.push(...renderFieldEnum(entity, "Order", orderable, orderHelpers(entity)));
    lines.push("");
    lines.push(...renderOrderStruct(entity));
    lines.push("");
    lines.push(...renderReadEntity(entity, table.name));
    return lines.join("\n") + "\n";
}

/** Render every generated file, keyed by file name (including the barrel). */
export function generateQueryModules(tables: Map<string, Table>, spec?: SpecModel): Map<string, string> {
    const entities = [...tables.values()]
        .filter((table) => table.queries.includes("query"))
        .sort((a, b) => a.interfaceName.localeCompare(b.interfaceName));

    const files = new Map<string, string>();
    const lines: string[] = [HEADER, ""];
    for (const table of entities) {
        const module = queryFunctionName(table.interfaceName);
        files.set(`${module}.rs`, renderQueryModule(table, spec));
        lines.push(`mod ${module};`);
    }
    if (entities.length > 0) {
        lines.push("");
    }
    for (const table of entities) {
        lines.push(`pub use ${queryFunctionName(table.interfaceName)}::*;`);
    }
    files.set(MODULE_FILE, lines.join("\n") + "\n");
    return files;
}

/** Remove the generated modules the spec no longer declares, so an entity that drops a read leaves no file. */
function pruneStale(outDir: string, keep: Set<string>): void {
    for (const entry of readdirSync(outDir, { withFileTypes: true })) {
        if (!entry.isFile() || !entry.name.startsWith("query_") || !entry.name.endsWith(".rs") || keep.has(entry.name)) {
            continue;
        }
        const file = join(outDir, entry.name);
        if (readFileSync(file, "utf8").split("\n", 1)[0] === HEADER) {
            rmSync(file);
        }
    }
}

/** Write the query modules for a parsed spec and return the exit code. */
export function run(spec: SpecModel, argv: readonly string[] = process.argv, output: Output = console): number {
    const { tables, diagnostics } = buildSpecTables(spec);

    for (const diagnostic of diagnostics) {
        output.error(`${diagnostic.filePath}:${diagnostic.line}: ${diagnostic.message}`);
    }
    if (diagnostics.length > 0) {
        return 1;
    }

    const outIndex = argv.indexOf("--out");
    const outDir = outIndex === -1 ? DEFAULT_OUT_DIR : argv[outIndex + 1];
    if (!outDir) {
        output.error("--out needs a directory");
        return 1;
    }

    const files = generateQueryModules(tables, spec);
    mkdirSync(outDir, { recursive: true });
    for (const [name, content] of files) {
        writeFileSync(join(outDir, name), content);
    }
    pruneStale(outDir, new Set(files.keys()));
    output.log(`wrote ${files.size} Rust query file(s) to ${outDir}`);
    return 0;
}

if (import.meta.main) {
    process.exitCode = run(loadSpec());
}
