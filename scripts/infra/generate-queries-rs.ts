/** The `selection` call as rustfmt writes it: one line while it fits, else the `map` on its own line. */
function selectionCall(field: string): string[] {
    const oneLine = `        flat_filter::selection(deserializer, ${field}::from_column).map(Self)`;
    return oneLine.length <= MAX_LINE_WIDTH
        ? [oneLine]
        : [
              `        flat_filter::selection(deserializer, ${field}::from_column)`,
              "            .map(Self)",
          ];
}

/** Render the selection a read carries: on the wire, an object naming each selected column. */
function renderSelectStruct(entity: string): string[] {
    const select = `${entity}Selection`;
    const field = `${entity}SelectField`;
    return [
        `/// The columns a \`${entity}\` read selects; empty selects every one.`,
        "///",
        "/// On the wire it is an object naming each column, as the TypeScript read sends it.",
        "#[derive(Clone, Debug, Default, PartialEq)]",
        `pub struct ${select}(pub Vec<${field}>);`,
        "",
        `impl serde::Serialize for ${select} {`,
        "    fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {",
        "        let mut map = serializer.serialize_map(Some(self.0.len()))?;",
        "        for field in &self.0 {",
        "            map.serialize_entry(field.as_str(), &true)?;",
        "        }",
        "        map.end()",
        "    }",
        "}",
        "",
        `impl<'de> serde::Deserialize<'de> for ${select} {`,
        "    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {",
        ...selectionCall(field),
        "    }",
        "}",
    ];
}

/** True when rustfmt keeps a `format!(...)` invocation of this text on one line: `fn_call_width` includes it. */
function formatInlines(text: string): boolean {
    return `format!(${JSON.stringify(text)})`.length <= FN_CALL_WIDTH;
}

/** A call as rustfmt writes it: one line when it fits, one argument per line otherwise. */
function call(expression: string, args: string[], indent: number, suffix = ""): string[] {
    const pad = " ".repeat(indent);
    const oneLine = `${pad}${expression}(${args.join(", ")})${suffix}`;
    if (oneLine.length <= MAX_LINE_WIDTH) {
        return [oneLine];
    }
    return [`${pad}${expression}(`, ...args.map((arg) => `${pad}    ${arg},`), `${pad})${suffix}`];
}

/** The wire key one comparison is written as, e.g. `tenantId__eq`. */
function wireKey(column: string, operator: QueryOperator): string {
    return `${column}${FILTER_SEPARATOR}${operator}`;
}

/** The Rust payload of one operator's variant: none for a null test, two values for a range, a list for a set. */
function operatorPayload(operator: QueryOperator, field: FilterFieldInfo): string {
    switch (operatorArity(operator)) {
        case 0:
            return "";
        case 2:
            return `(${field.valueType}, ${field.valueType})`;
        case "list":
            return `(Vec<${field.valueType}>)`;
        default:
            return `(${field.valueType})`;
    }
}

/** The planner call that lowers one operator's variant, split so it lays out like rustfmt writes it. */
function operatorLowering(operator: QueryOperator, field: FilterFieldInfo): { fn: string; args: string[] } {
    const args = [JSON.stringify(field.name), `SqlType::${field.sqlType}`, `FilterOperator::${FILTER_OPERATORS[operator]}`];
    switch (operatorArity(operator)) {
        case 0:
            return { fn: "TypedFilter::null_test", args };
        case 2:
            return { fn: "TypedFilter::pair", args: [...args, "lower", "upper"] };
        case "list":
            return { fn: "TypedFilter::list", args: [...args, "values"] };
        default:
            return { fn: "TypedFilter::one", args: [...args, "value"] };
    }
}

/** The binding an operator's variant payload takes, e.g. `Self::Any(values)`. */
function variantBinding(operator: QueryOperator, variant: string): string {
    switch (operatorArity(operator)) {
        case 0:
            return `Self::${variant}`;
        case 2:
            return `Self::${variant}(lower, upper)`;
        case "list":
            return `Self::${variant}(values)`;
        default:
            return `Self::${variant}(value)`;
    }
}

/** Render one filter column's comparisons, e.g. `InvoiceTenantIdFilter`. */
function renderFilterType(entity: string, field: FilterFieldInfo): string[] {
    const name = filterTypeName(entity, field.name);
    const keys = field.operators.map((operator) => wireKey(field.name, operator));
    const lines: string[] = [
        `/// A comparison on \`${entity}.${field.name}\`, limited to the operators \`@queryFilter ops=${field.operators.join(",")}\` whitelists.`,
        "///",
        `/// On the wire it is one flat entry, such as \`{"${keys[0]}": …}\`.`,
        "#[derive(Clone, Debug, PartialEq)]",
        `pub enum ${name} {`,
    ];
    for (const operator of field.operators) {
        lines.push(`    ${variantIdentifier(operator)}${operatorPayload(operator, field)},`);
    }
    lines.push("}");
    lines.push("");

    // The wire shape is the read's, not the enum's: one `column__operator` key per comparison.
    lines.push(`impl serde::Serialize for ${name} {`);
    lines.push("    fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {");
    lines.push("        match self {");
    for (const operator of field.operators) {
        const binding = variantBinding(operator, variantIdentifier(operator));
        const key = JSON.stringify(wireKey(field.name, operator));
        // A range writes its pair as an array and a null test its `true`, which is what the TypeScript read sends.
        const arity = operatorArity(operator);
        const payload = arity === 0 ? "&true" : arity === 2 ? "&[lower, upper]" : arity === "list" ? "values" : "value";
        const arm = `            ${binding} => flat_filter::serialize(${key}, ${payload}, serializer),`;
        if (arm.length <= MAX_LINE_WIDTH) {
            lines.push(arm);
        } else {
            lines.push(`            ${binding} => {`);
            lines.push(...call("flat_filter::serialize", [key, payload, "serializer"], 16, ""));
            lines.push("            }");
        }
    }
    lines.push("        }");
    lines.push("    }");
    lines.push("}");
    lines.push("");
    lines.push(`impl<'de> serde::Deserialize<'de> for ${name} {`);
    lines.push("    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {");
    lines.push("        flat_filter::deserialize(deserializer, |key, value| match key {");
    for (const operator of field.operators) {
        const phrase = JSON.stringify(wireKey(field.name, operator));
        const variant = variantIdentifier(operator);
        const arity = operatorArity(operator);
        if (arity === 2) {
            // A range arrives as the two-element array `between` was written with.
            lines.push(`            ${phrase} => {`);
            lines.push("                let (lower, upper) = flat_filter::payload(key, value)?;");
            lines.push(`                Ok(Self::${variant}(lower, upper))`);
            lines.push("            }");
            continue;
        }
        if (arity === 0) {
            // A null test carries `true`, so a `false` payload is rejected rather than read as a test.
            lines.push(`            ${phrase} => {`);
            lines.push("                flat_filter::null_test(key, value)?;");
            lines.push(`                Ok(Self::${variant})`);
            lines.push("            }");
            continue;
        }
        lines.push(`            ${phrase} => Ok(Self::${variant}(flat_filter::payload(key, value)?)),`);
    }
    const message = `unknown filter \`{other}\` on \`${entity}.${field.name}\``;
    if (formatInlines(message)) {
        lines.push(`            other => Err(format!(${JSON.stringify(message)})),`);
    } else {
        lines.push("            other => Err(format!(");
        lines.push(`                ${JSON.stringify(message)}`);
        lines.push("            )),");
    }
    lines.push("        })");
    lines.push("    }");
    lines.push("}");
    lines.push("");
    lines.push(`impl ${name} {`);
    lines.push("    /// The typed filter the planner binds.");
    lines.push("    ///");
    lines.push("    /// # Errors");
    lines.push("    ///");
    lines.push("    /// Returns [`ReadError::Encode`] when the value has no JSON form.");
    lines.push("    pub(crate) fn into_typed_filter(self) -> Result<TypedFilter, ReadError> {");
    lines.push("        Ok(match self {");
    for (const operator of field.operators) {
        const binding = variantBinding(operator, variantIdentifier(operator));
        const { fn, args } = operatorLowering(operator, field);
        // A null test binds nothing, so it is the one lowering that cannot fail.
        const suffix = operatorArity(operator) === 0 ? "" : "?";
        const oneLine = `            ${binding} => ${fn}(${args.join(", ")})${suffix},`;
        if (oneLine.length <= MAX_LINE_WIDTH) {
            lines.push(oneLine);
        } else if (args.join(", ").length <= FN_CALL_WIDTH) {
            lines.push(`            ${binding} => {`);
            lines.push(...call(fn, args, 16, suffix));
            lines.push("            }");
        } else {
            lines.push(`            ${binding} => ${fn}(`);
            for (const arg of args) {
                lines.push(`                ${arg},`);
            }
            lines.push(`            )${suffix},`);
        }
    }
    lines.push("        })");
    lines.push("    }");
    lines.push("}");
    return lines;
}

/** Render the entity's filter enum: one variant per column, and the `or` group the wire carries. */
function renderFilterEnum(entity: string, fields: FilterFieldInfo[]): string[] {
    const filter = `${entity}Filter`;
    const lines: string[] = [
        `/// A filter over \`${entity}\`: a comparison on one of its columns, or a group of filters.`,
        `/// A read's filters are combined with \`and\`, so a column may appear more than once.`,
        `/// See docs/rust-queries.md.`,
        "",
    ];
    // `untagged` is what lets a column variant serialize as its own flat entry rather than a wrapper.
    lines.push("#[derive(Clone, Debug, PartialEq, serde::Deserialize, serde::Serialize)]");
    lines.push("#[serde(untagged)]");
    lines.push(`pub enum ${filter} {`);
    for (const field of fields) {
        lines.push(`    /// A comparison on \`${field.name}\`.`);
        lines.push(`    ${fieldVariant(field.name)}(${filterTypeName(entity, field.name)}),`);
    }
    lines.push("    /// A group of filters, combined the way `kind` says.");
    lines.push("    Group {");
    lines.push("        /// Whether every branch must match or any may.");
    lines.push("        kind: FilterKind,");
    lines.push("        /// The branches; each is a comparison or, in turn, a group.");
    lines.push("        filters: Vec<Self>,");
    lines.push("    },");
    lines.push("}");
    lines.push("");

    // One `From` per column type, so `filter(...)` takes a column's filter directly.
    for (const field of fields) {
        const name = filterTypeName(entity, field.name);
        lines.push(`impl From<${name}> for ${filter} {`);
        lines.push(`    fn from(filter: ${name}) -> Self {`);
        lines.push(`        Self::${fieldVariant(field.name)}(filter)`);
        lines.push("    }");
        lines.push("}");
        lines.push("");
    }

    lines.push(`impl ${filter} {`);
    lines.push("    /// The typed filters this names, in the order the builder binds them.");
    lines.push("    ///");
    lines.push("    /// # Errors");
    lines.push("    ///");
    lines.push("    /// Returns [`ReadError::Encode`] when a value has no JSON form.");
    lines.push("    pub(crate) fn into_typed_filters(self) -> Result<Vec<TypedFilter>, ReadError> {");
    lines.push("        match self {");
    for (const field of fields) {
        const arm = `            Self::${fieldVariant(field.name)}(filter) => Ok(vec![filter.into_typed_filter()?]),`;
        if (arm.length <= MAX_LINE_WIDTH) {
            lines.push(arm);
        } else {
            lines.push(`            Self::${fieldVariant(field.name)}(filter) => {`);
            lines.push("                Ok(vec![filter.into_typed_filter()?])");
            lines.push("            }");
        }
    }
    lines.push("            Self::Group { kind, filters } => {");
    lines.push("                let mut typed = Vec::new();");
    lines.push("                for filter in filters {");
    lines.push("                    typed.extend(filter.into_typed_filters()?);");
    lines.push("                }");
    lines.push("                Ok(match typed.len() {");
    lines.push("                    0 => Vec::new(),");
    lines.push("                    1 => typed,");
    lines.push("                    _ => vec![TypedFilter::group(kind.combinator(), typed)],");
    lines.push("                })");
    lines.push("            }");
    lines.push("        }");
    lines.push("    }");
    lines.push("}");
    return lines;
}

/** Render every column's filter type, then the umbrella enum. */
export function renderFilters(entity: string, fields: FilterFieldInfo[]): string[] {
    const lines: string[] = [];
    for (const field of fields) {
        lines.push(...renderFilterType(entity, field));
        lines.push("");
    }
    lines.push(...renderFilterEnum(entity, fields));
    return lines;
}

