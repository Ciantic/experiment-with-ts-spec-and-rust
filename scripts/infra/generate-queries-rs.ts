/** The `SqlType` variant for a column, so an unlisted textual type still binds as text. */
export function sqlTypeVariant(sqlType: string): string {
    return SQL_TYPES[sqlType] ?? "Text";
}

/** The barrel re-exporting every generated query module. */
const MODULE_FILE = "mod.rs";

/** The module and function name for an entity, e.g. `Invoice` -> `query_invoice`. */
export function queryFunctionName(entity: string): string {
    return `query_${snakeName(entity)}`;
}

/** The module file for an entity's read, e.g. `Invoice` -> `query_invoice.rs`. */
export function queryFileName(entity: string): string {
    return `${queryFunctionName(entity)}.rs`;
}

/** The selected type a read decodes into, e.g. `models::domain::invoicing_service::invoice::InvoiceSelect`. */
export function selectTypePath(table: Table): string {
    return rustModelItemPath(table.importSpecifier, `${table.interfaceName}Select`);
}

/** The columns `@inlined` branches reach through their branch, so a read does not select them by name. */
function inlinedColumns(table: Table): Set<string> {
    const columns = new Set<string>();
    for (const relation of table.relations.values()) {
        if (relation.kind === "inlined") {
            for (const column of Object.values(relation.columns ?? {})) {
                columns.add(column);
            }
        }
    }
    return columns;
}

/** The columns an entity's read may select: every physical column a branch does not own. */
export function selectableFields(table: Table): string[] {
    const inlined = inlinedColumns(table);
    return table.columns.map((column) => column.name).filter((name) => !inlined.has(name));
}

/** A filter field: its column, the Postgres type it binds as, and the Rust type of a value it compares. */
export interface FilterFieldInfo {
    name: string;
    sqlType: string;
    /** The model's Rust type for this column; `Value` when the spec shape has no Rust equivalent. */
    valueType: string;
    /** `use` statements for a value type declared in another model module. */
    imports: string[];
}

/** The fields an entity exposes as filters, with the model type each value must have. */
export function filterFields(table: Table, spec?: SpecModel): FilterFieldInfo[] {
    const entity = spec?.interfaces.get(table.interfaceName);
    return table.columns
        .filter((column) => column.queryFilter !== undefined)
        .map((column) => {
            const property = entity?.properties.find((candidate) => candidate.name === column.name);
            const resolved = property === undefined || spec === undefined ? undefined : rustValueType(spec, property);
            return {
                name: column.name,
                sqlType: sqlTypeVariant(column.sqlType),
                valueType: resolved?.type ?? "Value",
                imports: resolved?.imports ?? [],
            };
        });
}

/** The field names an entity exposes as ordering keys: its `@queryOrderBy` scalar columns. */
export function orderFields(table: Table): string[] {
    return table.columns.filter((column) => column.queryOrder !== undefined).map((column) => column.name);
}

/** The enum name of one field set, e.g. `Invoice` + `Filter` -> `InvoiceFilterField`. */
export function fieldEnumName(entity: string, kind: "Select" | "Filter" | "Order"): string {
    return `${entity}${kind}Field`;
}

/** The variant for a field, e.g. `tenantId` -> `TenantId`. */
function fieldVariant(field: string): string {
    return variantIdentifier(field);
}

/** A field of an enum, with the Postgres type it binds as when it is a filter. */
export interface FieldInfo {
    name: string;
    sqlType?: string;
}

/** Render an enum of one entity's fields: the columns it names, plus the helpers the caller builds with. */
function renderFieldEnum(entity: string, kind: "Select" | "Filter" | "Order", fields: FieldInfo[], helpers: string[]): string[] {
    const name = fieldEnumName(entity, kind);
    const lines: string[] = fields.length === 0 ? [`pub enum ${name} {}`] : [`pub enum ${name} {`];
    for (const field of fields) {
        lines.push(`    ${fieldVariant(field.name)},`);
    }
    if (fields.length > 0) {
        lines.push("}");
    }
    lines.push("");
    lines.push(`impl ${name} {`);
    if (fields.length === 0) {
        lines.push("    /// Every field; empty because the entity declares none.");
        lines.push("    pub const ALL: &'static [Self] = &[];");
        lines.push("");
        lines.push("    /// The column this field names.");
        lines.push("    #[must_use]");
        lines.push("    pub const fn as_str(self) -> &'static str {");
        lines.push("        match self {}");
        lines.push("    }");
    } else {
        lines.push("    /// Every field, in declaration order.");
        lines.push("    #[rustfmt::skip]");
        lines.push("    pub const ALL: &'static [Self] = &[");
        for (const field of fields) {
            lines.push(`        Self::${fieldVariant(field.name)},`);
        }
        lines.push("    ];");
        lines.push("");
        lines.push("    /// The column this field names.");
        lines.push("    #[must_use]");
        lines.push("    pub const fn as_str(self) -> &'static str {");
        lines.push("        match self {");
        for (const field of fields) {
            lines.push(`            Self::${fieldVariant(field.name)} => ${JSON.stringify(field.name)},`);
        }
        lines.push("        }");
        lines.push("    }");
    }
    if (kind === "Filter") {
        lines.push("");
        lines.push("    /// The Postgres type this column binds as.");
        lines.push("    #[must_use]");
        lines.push("    pub const fn sql_type(self) -> SqlType {");
        lines.push("        match self {");
        for (const field of fields) {
            lines.push(`            Self::${fieldVariant(field.name)} => SqlType::${field.sqlType ?? "Text"},`);
        }
        lines.push("        }");
        lines.push("    }");
    }
    if (helpers.length > 0) {
        lines.push("");
        for (const helper of helpers) {
            lines.push(helper.length === 0 ? helper : `    ${helper}`);
        }
    }
    lines.push("}");
    lines.push("");
    lines.push(`impl std::fmt::Display for ${name} {`);
    lines.push("    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {");
    lines.push("        f.write_str(self.as_str())");
    lines.push("    }");
    lines.push("}");
    return lines;
}

/** The derive line above a field enum. */
function fieldEnumDerive(): string {
    return "#[derive(Clone, Copy, Debug, Eq, Hash, Ord, PartialEq, PartialOrd)]";
}

/** The `select` helper of a selectable field. */
function selectHelper(): string[] {
    return [
        "/// The select-list entry for this column.",
        "#[must_use]",
        "pub fn select(self) -> SelectColumn {",
        "    SelectColumn::Name(self.as_str().to_owned())",
        "}",
    ];
}

/** A function signature as rustfmt writes it: one line when it fits, one parameter per line otherwise. */
function signature(name: string, params: string[], returns: string, indent = 0, visibility = "pub "): string[] {
    const prefix = " ".repeat(indent);
    const oneLine = `${prefix}${visibility}fn ${name}(${params.join(", ")}) -> ${returns} {`;
    if (oneLine.length <= MAX_LINE_WIDTH) {
        return [oneLine];
    }
    const lines = [`${prefix}${visibility}fn ${name}(`];
    for (const param of params) {
        lines.push(`${prefix}    ${param},`);
    }
    lines.push(`${prefix}) -> ${returns} {`);
    return lines;
}

/** Render the entity's typed filter tree, so a read cannot filter on another table's column. */
function renderFilterStruct(entity: string): string[] {
    const filter = `${entity}Filter`;
    const field = `${entity}FilterField`;
    const bind = signature("bind", [`field: ${field}`, "operator: FilterOperator", "value: impl BindValue"], "Result<Self, ReadError>", 4, "");
    return [
        `/// A filter over \`${entity}\`: one comparison on a \`${field}\`, or a group of them.`,
        `/// The read's filters are combined with \`and\`.`,
        "#[derive(Clone, Debug, PartialEq)]",
        `pub enum ${filter} {`,
        "    /// One comparison on one column.",
        "    Condition {",
        `        field: ${field},`,
        "        operator: FilterOperator,",
        "        value: Option<Value>,",
        "    },",
        "    /// Every child must match.",
        "    And(Vec<Self>),",
        "    /// Any child may match.",
        "    Or(Vec<Self>),",
        "}",
        "",
        `impl ${filter} {`,
        "    /// One comparison on one column; a typed builder is the way a caller reaches this.",
        ...signature("condition", [`field: ${field}`, "operator: FilterOperator", "value: Option<Value>"], "Self", 4, ""),
        "        Self::Condition {",
        "            field,",
        "            operator,",
        "            value,",
        "        }",
        "    }",
        "",
        "    /// One comparison on one column, converting `value` to a bind value.",
        "    ///",
        "    /// # Errors",
        "    ///",
        "    /// Returns [`ReadError::Encode`] when the value has no JSON form.",
        ...bind,
        "        Ok(Self::condition(",
        "            field,",
        "            operator,",
        "            Some(value.to_bind_value()?),",
        "        ))",
        "    }",
        "",
        "    /// Every child must match; an empty group matches everything.",
        "    #[must_use]",
        "    pub fn and(filters: impl IntoIterator<Item = Self>) -> Self {",
        "        Self::And(filters.into_iter().collect())",
        "    }",
        "",
        "    /// Any child may match; an empty group matches nothing.",
        "    #[must_use]",
        "    pub fn or(filters: impl IntoIterator<Item = Self>) -> Self {",
        "        Self::Or(filters.into_iter().collect())",
        "    }",
        "",
        "    /// The typed filter the planner binds.",
        "    #[must_use]",
        "    pub fn into_typed_filter(self) -> TypedFilter {",
        "        match self {",
        "            Self::Condition {",
        "                field,",
        "                operator,",
        "                value,",
        "            } => TypedFilter::condition(field.as_str(), field.sql_type(), operator, value),",
        "            Self::And(filters) => {",
        "                let children = filters.into_iter().map(Self::into_typed_filter).collect();",
        "                TypedFilter::group(Combinator::And, children)",
        "            }",
        "            Self::Or(filters) => {",
        "                let children = filters.into_iter().map(Self::into_typed_filter).collect();",
        "                TypedFilter::group(Combinator::Or, children)",
        "            }",
        "        }",
        "    }",
        "}",
    ];
}

/** The constant a filter field's builder is reached through, e.g. `tenantId` -> `TENANT_ID`. */
export function filterConstantName(field: string): string {
    return snakeName(field).toUpperCase();
}

/** The builder type of one filter field, e.g. `Invoice` + `tenantId` -> `InvoiceTenantIdFilter`. */
export function filterBuilderName(entity: string, field: string): string {
    return `${entity}${variantIdentifier(field)}Filter`;
}

/** The methods a field's filter builder carries, each taking the column's own value type. */
function filterBuilderMethods(entity: string, field: FilterFieldInfo): string[] {
    const filter = `${entity}Filter`;
    const value = field.valueType;
    const method = (name: string, params: string[], returns: string): string[] => signature(name, params, returns, 4);

    return [
        "    /// The column this filter targets.",
        "    #[must_use]",
        `    pub const fn field(self) -> ${entity}FilterField {`,
        "        self.0",
        "    }",
        "",
        `    /// \`${field.name} = value\`.`,
        "    ///",
        "    /// # Errors",
        "    ///",
        "    /// Returns [`ReadError::Encode`] when the value has no JSON form.",
        ...method("eq", ["self", `value: impl Borrow<${value}>`], `Result<${filter}, ReadError>`),
        `        ${filter}::bind(self.0, FilterOperator::Eq, value.borrow())`,
        "    }",
        "",
        `    /// \`${field.name} <> value\`.`,
        "    ///",
        "    /// # Errors",
        "    ///",
        "    /// Returns [`ReadError::Encode`] when the value has no JSON form.",
        ...method("ne", ["self", `value: impl Borrow<${value}>`], `Result<${filter}, ReadError>`),
        `        ${filter}::bind(self.0, FilterOperator::Neq, value.borrow())`,
        "    }",
        "",
        `    /// \`${field.name} = any(values)\`, bound as one array parameter.`,
        "    ///",
        "    /// # Errors",
        "    ///",
        "    /// Returns [`ReadError::Encode`] when a value has no JSON form.",
        ...method(
            "any",
            ["self", `values: impl IntoIterator<Item = impl Borrow<${value}>>`],
            `Result<${filter}, ReadError>`,
        ),
        "        let mut bound = Vec::new();",
        "        for value in values {",
        "            bound.push(value.borrow().to_bind_value()?);",
        "        }",
        `        Ok(${filter}::condition(`,
        "            self.0,",
        "            FilterOperator::Any,",
        "            Some(Value::Array(bound)),",
        "        ))",
        "    }",
        "",
        `    /// \`${field.name} is null\`.`,
        "    #[must_use]",
        ...method("is_null", ["self"], filter),
        `        ${filter}::condition(self.0, FilterOperator::IsNull, None)`,
        "    }",
        "",
        `    /// \`${field.name} is not null\`.`,
        "    #[must_use]",
        ...method("is_not_null", ["self"], filter),
        `        ${filter}::condition(self.0, FilterOperator::IsNotNull, None)`,
        "    }",
    ];
}

/** Render one field's typed filter builder. */
function renderFilterBuilder(entity: string, field: FilterFieldInfo): string[] {
    const name = filterBuilderName(entity, field.name);
    return [
        `/// The \`${field.name}\` filter of \`${entity}\`.`,
        "#[derive(Clone, Copy, Debug, Eq, PartialEq)]",
        `pub struct ${name}(${entity}FilterField);`,
        "",
        `impl ${name} {`,
        ...filterBuilderMethods(entity, field),
        "}",
    ];
}

/** Render the typed filter builders of every filterable field, plus the constant each is reached through. */
export function renderFilterBuilders(entity: string, fields: FilterFieldInfo[]): string[] {
    const enumName = `${entity}FilterField`;
    const lines: string[] = [];

    if (fields.length > 0) {
        lines.push(`impl ${enumName} {`);
        for (const field of fields) {
            const builder = filterBuilderName(entity, field.name);
            const constant = filterConstantName(field.name);
            const oneLine = `    pub const ${constant}: ${builder} = ${builder}(Self::${fieldVariant(field.name)});`;
            lines.push(`    /// The \`${field.name}\` typed filter builder.`);
            if (oneLine.length <= MAX_LINE_WIDTH) {
                lines.push(oneLine);
            } else {
                lines.push(`    pub const ${constant}: ${builder} =`);
                lines.push(`        ${builder}(Self::${fieldVariant(field.name)});`);
            }
        }
        lines.push("}");
        lines.push("");
    }

    fields.forEach((field, index) => {
        if (index > 0) {
            lines.push("");
        }
        lines.push(...renderFilterBuilder(entity, field));
    });
    return lines;
}

