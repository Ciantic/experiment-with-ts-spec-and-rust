/** Turn `EInvoiceAddress` into `e_invoice_address`. */
export function snakeName(name: string): string {
    return name
        .replace(
            /([A-Z]+)([A-Z][a-z])/gu,
            (match: string, run: string, word: string, offset: number, whole: string) => {
                const after = whole[offset + match.length] ?? "";
                // An all-caps prefix followed by a lowercase tail and a digit is one word, such as `UUIDv7`.
                return run.length === 1 || !/\d/u.test(after) ? `${run}_${word}` : match;
            },
        )
        .replace(/([a-z0-9])([A-Z])/gu, "$1_$2")
        .replace(/[^A-Za-z0-9]+/gu, "_")
        .replace(/^_+|_+$/gu, "")
        .toLowerCase();
}

/** Turn `api-key` into `ApiKey`, for an enum variant. */
export function pascalName(name: string): string {
    const words = name
        .replace(/([a-z0-9])([A-Z])/gu, "$1 $2")
        .split(/[^A-Za-z0-9]+/u)
        .filter((word) => word.length > 0);
    const joined = words.map((word) => `${word.slice(0, 1).toUpperCase()}${word.slice(1).toLowerCase()}`).join("");
    return joined.length === 0 ? "Unknown" : joined;
}

/** A field identifier, raw when it collides with a keyword. */
function fieldIdentifier(name: string): string {
    const snake = snakeName(name);
    return RESERVED.has(snake) ? `r#${snake}` : snake;
}

/** A variant identifier, suffixed when it collides with a keyword. */
function variantIdentifier(name: string): string {
    const variant = pascalName(name);
    return RESERVED.has(variant) ? `${variant}_` : variant;
}

/** The directory components of a spec source file, relative to `spec/src`. */
function specDirectories(filePath: string): string[] {
    const relative = relativePath(SPEC_SRC_ROOT, filePath);
    const parts = relative.split(/[\\/]/u);
    parts.pop();
    return parts;
}

/** The Rust module name for a directory, e.g. `invoicing-service` -> `invoicing_service`. */
function directoryModule(rawName: string): string {
    return snakeName(rawName);
}

/** The Rust module name for a spec source file, e.g. `EInvoiceAddress.ts` -> `e_invoice_address`. */
function fileModule(filePath: string): string {
    return snakeName(basename(filePath, ".ts"));
}

/** The absolute Rust path of an item, e.g. `crate::domain::invoicing_service::primitives::money::Money`. */
function itemPath(filePath: string, item: string): string {
    const components = [...specDirectories(filePath).map(directoryModule), fileModule(filePath), item];
    return ["crate", "domain", ...components].join("::");
}

/** The output path of a spec source file, keeping its spec directories and using a Rust file name. */
function outputPath(filePath: string): string {
    return [...specDirectories(filePath), `${fileModule(filePath)}.rs`].join("/");
}

/** The Rust type a `@pgType` maps to, following Postgres' own spellings. */
function storageType(pgType: string): string | undefined {
    return STORAGE_TYPES[STORAGE_ALIASES[pgType] ?? pgType];
}

/** Record an import when the item is declared in another spec source file. */
function addImport(context: RenderContext, filePath: string, item: string): void {
    if (filePath === context.currentFilePath) {
        return;
    }
    context.imports.add(`use ${itemPath(filePath, item)};`);
}

/** Map one spec type to a Rust type, or undefined when the shape has no Rust equivalent. */
function renderType(type: SpecType, context: RenderContext): string | undefined {
    switch (type.kind) {
        case "keyword":
            return KEYWORD_TYPES[type.name];
        case "stringLiteral":
            return "String";
        case "numberLiteral":
            return "f64";
        case "array": {
            const element = renderType(type.element, context) ?? "serde_json::Value";
            return `Vec<${element}>`;
        }
        case "reference":
            return renderReference(type.name, context);
        case "intersection":
        case "union": {
            for (const member of type.members) {
                const rendered = renderType(member, context);
                if (rendered !== undefined) {
                    return rendered;
                }
            }
            return undefined;
        }
        case "object":
            return "serde_json::Value";
        case "missing":
        case "unknown":
            return undefined;
    }
}

/** Map a named type through the spec's aliases and entities, adding an import when it lives elsewhere. */
function renderReference(name: string, context: RenderContext): string | undefined {
    const keyword = KEYWORD_TYPES[name];
    if (keyword !== undefined) {
        return keyword;
    }

    const alias = context.spec.aliases.get(name);
    if (alias !== undefined) {
        if (alias.typeParameters.length === 0 && context.generatedAliases.has(name)) {
            addImport(context, alias.filePath, name);
            return name;
        }
        return renderAliasBase(alias, context);
    }

    const entity = context.spec.interfaces.get(name);
    if (entity !== undefined) {
        addImport(context, entity.filePath, name);
        return name;
    }

    return undefined;
}

/** The Rust type a generic or ungenerated alias stands for: its storage type, else its own type. */
function renderAliasBase(alias: SpecTypeAlias, context: RenderContext): string | undefined {
    if (alias.tags.pgType !== undefined) {
        const scalar = storageType(alias.tags.pgType);
        if (scalar !== undefined) {
            return scalar;
        }
    }
    return renderType(alias.type, context);
}

/** The derives a newtype takes: a float or JSON base cannot be ordered or hashed. */
function newtypeDerives(base: string): string {
    const ordered = !base.includes("f32") && !base.includes("f64") && !base.includes("serde_json::Value");
    return ordered
        ? "Clone, Debug, Default, Eq, Hash, Ord, PartialEq, PartialOrd, serde::Serialize, serde::Deserialize"
        : "Clone, Debug, Default, PartialEq, PartialOrd, serde::Serialize, serde::Deserialize";
}

/** Render a newtype over the alias's base type. */
function renderNewtype(name: string, base: string): string[] {
    return [`#[derive(${newtypeDerives(base)})]`, `pub struct ${name}(pub ${base});`];
}

/** The literal members of a string union and whether any other string is allowed. */
function stringUnion(type: SpecType, context: RenderContext): { literals: string[]; open: boolean } | undefined {
    if (type.kind !== "union") {
        return undefined;
    }
    const literals: string[] = [];
    let open = false;
    for (const member of type.members) {
        if (member.kind === "stringLiteral") {
            literals.push(member.value);
        } else if (renderType(member, context) === "String") {
            open = true;
        } else {
            return undefined;
        }
    }
    return { literals: [...new Set(literals)], open };
}

/** Render the manual serde implementation an open string enum needs, because it carries an unknown string. */
function renderOpenEnumSerde(name: string, literals: string[]): string[] {
    const lines = [
        `impl serde::Serialize for ${name} {`,
        "    fn serialize<S>(&self, serializer: S) -> Result<S::Ok, S::Error>",
        "    where",
        "        S: serde::Serializer,",
        "    {",
        "        match self {",
    ];
    for (const literal of literals) {
        lines.push(`            Self::${variantIdentifier(literal)} => serializer.serialize_str(${JSON.stringify(literal)}),`);
    }
    lines.push(
        "            Self::Other(value) => serializer.serialize_str(value),",
        "        }",
        "    }",
        "}",
        "",
        `impl<'de> serde::Deserialize<'de> for ${name} {`,
        "    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>",
        "    where",
        "        D: serde::Deserializer<'de>,",
        "    {",
        "        let value = <String as serde::Deserialize>::deserialize(deserializer)?;",
        "        Ok(match value.as_str() {",
    );
    for (const literal of literals) {
        lines.push(`            ${JSON.stringify(literal)} => Self::${variantIdentifier(literal)},`);
    }
    lines.push("            _ => Self::Other(value),", "        })", "    }", "}");
    return lines;
}

/** Render an alias whose type is a set of string literals. */
function renderStringEnum(name: string, literals: string[], open: boolean): string[] {
    if (literals.length === 0) {
        return renderNewtype(name, "String");
    }
    const lines = [
        open
            ? "#[derive(Clone, Debug, Default, Eq, Hash, Ord, PartialEq, PartialOrd)]"
            : "#[derive(Clone, Copy, Debug, Default, Eq, Hash, Ord, PartialEq, PartialOrd, serde::Serialize, serde::Deserialize)]",
        `pub enum ${name} {`,
    ];
    for (const [index, literal] of literals.entries()) {
        if (index === 0) {
            lines.push("    #[default]");
        }
        if (!open) {
            lines.push(`    #[serde(rename = ${JSON.stringify(literal)})]`);
        }
        lines.push(`    ${variantIdentifier(literal)},`);
    }
    if (open) {
        lines.push("    Other(String),");
    }
    lines.push("}");
    if (open) {
        lines.push("", ...renderOpenEnumSerde(name, literals));
    }
    return lines;
}

/** Render an alias whose type is an object literal as a struct. */
function renderObjectAlias(alias: SpecTypeAlias, type: Extract<SpecType, { kind: "object" }>, context: RenderContext): string[] {
    const lines = [
        "#[derive(Clone, Debug, Default, PartialEq, serde::Serialize, serde::Deserialize)]",
        '#[serde(rename_all = "camelCase")]',
        `pub struct ${alias.name} {`,
    ];
    for (const member of type.members) {
        const rendered = renderType(member.type, context) ?? "String";
        const name = fieldIdentifier(member.name);
        if (member.optional) {
            lines.push('    #[serde(default, skip_serializing_if = "Option::is_none")]');
        }
        if (name.startsWith("r#")) {
            lines.push(`    #[serde(rename = ${JSON.stringify(member.name)})]`);
        }
        lines.push(`    pub ${name}: ${member.optional ? `Option<${rendered}>` : rendered},`);
    }
    lines.push("}");
    return lines;
}

/** Render a primitive or a domain alias: an enum, an object, or a newtype. */
function renderAlias(alias: SpecTypeAlias, context: RenderContext): string[] {
    if (alias.typeParameters.length > 0) {
        return [];
    }

    const stringMembers = stringUnion(alias.type, context);
    if (stringMembers !== undefined) {
        return renderStringEnum(alias.name, stringMembers.literals, stringMembers.open);
    }

    if (alias.type.kind === "object") {
        return renderObjectAlias(alias, alias.type, context);
    }

    const base = renderType(alias.type, context);
    if (base === undefined) {
        context.diagnostics.push({ ...alias.location, message: `cannot map the type of \`${alias.name}\` to Rust` });
        return [];
    }
    return renderNewtype(alias.name, base);
}

/** The serde attribute that marks a field as presence-tracked, or as an optional value. */
function presenceAttribute(options: { present?: boolean; optional?: boolean }): string[] {
    if (options.present) {
        return ['    #[serde(default, skip_serializing_if = "Partial::is_unset")]'];
    }
    if (options.optional) {
        return ['    #[serde(default, skip_serializing_if = "Option::is_none")]'];
    }
    return [];
}

/** One field of a generated struct: its spec name, its Rust type, and how its absence reads on the wire. */
interface FieldShape {
    property: SpecProperty;
    rustType: string;
    present?: boolean;
    optional?: boolean;
}

/** Render one field, renaming a Rust keyword back to the spec's spelling on the wire. */
function renderField(shape: FieldShape): string[] {
    const identifier = fieldIdentifier(shape.property.name);
    const lines = presenceAttribute(shape);
    if (identifier.startsWith("r#")) {
        lines.push(`    #[serde(rename = ${JSON.stringify(shape.property.name)})]`);
    }
    lines.push(`    pub ${identifier}: ${shape.rustType},`);
    return lines;
}

/** Render a struct from its field shapes. */
function renderStruct(
    name: string,
    doc: string,
    serde: string,
    shapes: FieldShape[],
    context: RenderContext,
): string[] {
    if (shapes.some((shape) => shape.present || shape.rustType.includes("Partial<"))) {
        context.usesPartial = true;
    }
    const lines = [
        `/// ${doc}`,
        "#[derive(Clone, Debug, Default, PartialEq, serde::Serialize, serde::Deserialize)]",
        serde,
        `pub struct ${name} {`,
    ];
    for (const shape of shapes) {
        lines.push(...renderField(shape));
    }
    lines.push("}");
    return lines;
}

/** Render an entity as a serde struct, with camelCase field names on the wire. */
function renderEntity(entity: SpecInterface, context: RenderContext): string[] {
    const lines = [
        "#[derive(Clone, Debug, Default, PartialEq, serde::Serialize, serde::Deserialize)]",
        '#[serde(rename_all = "camelCase")]',
        `pub struct ${entity.name} {`,
    ];
    for (const property of entity.properties) {
        lines.push(
            ...renderField({
                property,
                rustType: property.optional
                    ? `Option<${renderPropertyType(property, context)}>`
                    : renderPropertyType(property, context),
                optional: property.optional,
            }),
        );
    }
    lines.push("}");
    return lines;
}

/** Render a property's type, reporting a shape that has no Rust equivalent. */
function renderPropertyType(property: SpecProperty, context: RenderContext): string {
    const rendered = renderType(property.type, context);
    if (rendered !== undefined) {
        return rendered;
    }
    context.diagnostics.push({
        ...property.location,
        message: `cannot map the type \`${property.typeText}\` of \`${property.name}\` to Rust`,
    });
    return "String";
}

/** The entity a field names, whether directly or as an array element; undefined for a scalar. */
function entityNameOf(type: SpecType, spec: SpecModel): string | undefined {
    if (type.kind === "reference") {
        return spec.interfaces.has(type.name) ? type.name : undefined;
    }
    if (type.kind === "array") {
        return entityNameOf(type.element, spec);
    }
    return undefined;
}

/** Import another entity's derived struct, naming it by suffix: `Customer` -> `CustomerSelect`. */
function addStructImport(context: RenderContext, target: string, suffix: string): void {
    const entity = context.spec.interfaces.get(target);
    if (entity === undefined) {
        return;
    }
    addImport(context, entity.filePath, `${target}${suffix}`);
}

/** The type a field takes in a selection, so a branch carries its target's selection. */
function selectType(property: SpecProperty, context: RenderContext): string {
    const target = entityNameOf(property.type, context.spec);
    let inner: string;
    if (target === undefined) {
        inner = renderPropertyType(property, context);
    } else {
        addStructImport(context, target, "Select");
        inner = property.type.kind === "array" ? `Vec<${target}Select>` : `${target}Select`;
    }
    return property.optional ? `Partial<Option<${inner}>>` : `Partial<${inner}>`;
}

/** The inner type of a written field: an `@inlined` branch nests its target's create shape. */
function writeInnerType(property: SpecProperty, inlined: ReadonlySet<string>, context: RenderContext): string {
    const target = entityNameOf(property.type, context.spec);
    if (target !== undefined && inlined.has(property.name)) {
        addStructImport(context, target, "Insert");
        return `${target}Insert`;
    }
    return renderPropertyType(property, context);
}

/** The field sets a create or an upsert derives from the spec. */
interface WriteSets {
    omitted: ReadonlySet<string>;
    defaulted: ReadonlySet<string>;
    inlined: ReadonlySet<string>;
    /** Columns the write must carry: the key it addresses and the version it claims. */
    locked: ReadonlySet<string>;
}

/** The fields a create or an upsert writes, from the omit, relax, and lock sets it derives. */
function writeShapes(entity: SpecInterface, sets: WriteSets, context: RenderContext): FieldShape[] {
    return entity.properties
        .filter((property) => !sets.omitted.has(property.name))
        .map((property) => {
            const inner = writeInnerType(property, sets.inlined, context);
            // A locked column addresses or claims the row, so neither omission nor a null can express it.
            if (sets.locked.has(property.name)) {
                return { property, rustType: inner };
            }
            // A nullable column with a default keeps three states: omitting it takes the default, and a null writes one.
            if (property.optional && sets.defaulted.has(property.name)) {
                return { property, rustType: `Partial<Option<${inner}>>`, present: true };
            }
            const optional = property.optional || sets.defaulted.has(property.name);
            return { property, rustType: optional ? `Option<${inner}>` : inner, ...(optional ? { optional } : {}) };
        });
}

/** The fields a create writes, as the model's own omit and relax sets describe them. */
function insertShapes(entity: SpecInterface, context: RenderContext): FieldShape[] {
    return writeShapes(
        entity,
        {
            omitted: new Set(omittedFromInsert(entity).map((property) => property.name)),
            defaulted: new Set(defaultedInsertProperties(entity).map((property) => property.name)),
            inlined: new Set(inlinedFromInsert(entity).map((property) => property.name)),
            locked: new Set(),
        },
        context,
    );
}

/** The fields an upsert writes: a create's set, plus the key and version it claims. */
function upsertShapes(entity: SpecInterface, context: RenderContext): FieldShape[] {
    return writeShapes(
        entity,
        {
            omitted: new Set(
                omittedFromInsert(entity)
                    .filter((property) => !property.tags.primaryKey)
                    .map((property) => property.name),
            ),
            defaulted: new Set(defaultedInsertProperties(entity).map((property) => property.name)),
            inlined: new Set(inlinedFromInsert(entity).map((property) => property.name)),
            locked: new Set(
                entity.properties
                    .filter((property) => property.tags.primaryKey || property.tags.version)
                    .map((property) => property.name),
            ),
        },
        context,
    );
}

/** The fields a patch writes: a create's, less the creation clock, plus the key and version it locks. */
function patchShapes(entity: SpecInterface, context: RenderContext): FieldShape[] {
    const omitted = new Set(omittedFromPatch(entity).map((property) => property.name));
    const nullable = new Set(nullablePatchProperties(entity).map((property) => property.name));
    const inlined = new Set(inlinedFromInsert(entity).map((property) => property.name));
    return entity.properties
        .filter((property) => !omitted.has(property.name))
        .map((property) => {
            const target = entityNameOf(property.type, context.spec);
            let inner: string;
            if (target !== undefined && inlined.has(property.name)) {
                addStructImport(context, target, "Insert");
                inner = `${target}Insert`;
            } else {
                inner = renderPropertyType(property, context);
            }
            const locked = property.tags.primaryKey || property.tags.version;
            if (locked) {
                return { property, rustType: inner };
            }
            const present = { present: true };
            return {
                property,
                rustType: nullable.has(property.name) ? `Partial<Option<${inner}>>` : `Partial<${inner}>`,
                ...present,
            };
        });
}

/** The key a delete addresses and a `rows` watch carries. */
function primaryKeyShapes(entity: SpecInterface, context: RenderContext): FieldShape[] {
    return primaryKeyProperties(entity).map((property) => ({ property, rustType: renderPropertyType(property, context) }));
}

/** Render every struct derived from one entity: the row, its selection, and its write shapes. */
function renderEntityStructs(entity: SpecInterface, context: RenderContext): string[][] {
    const blocks = [
        renderEntity(entity, context),
        renderStruct(
            `${entity.name}Select`,
            `The selected shape of ${entity.name}: a field is set when the read selected it.`,
            '#[serde(rename_all = "camelCase")]',
            entity.properties.map((property) => ({
                property,
                rustType: selectType(property, context),
                present: true,
            })),
            context,
        ),
        renderStruct(
            `${entity.name}Insert`,
            "The fields a create writes: a defaulted column may be omitted, and the database fills it.",
            '#[serde(rename_all = "camelCase", deny_unknown_fields)]',
            insertShapes(entity, context),
            context,
        ),
        renderStruct(
            `${entity.name}Upsert`,
            "The fields an upsert writes: what a create carries, plus the key and version it claims.",
            '#[serde(rename_all = "camelCase", deny_unknown_fields)]',
            upsertShapes(entity, context),
            context,
        ),
        renderStruct(
            `${entity.name}Patch`,
            "A partial update: every field is optional except the key and the version.",
            '#[serde(rename_all = "camelCase", deny_unknown_fields)]',
            patchShapes(entity, context),
            context,
        ),
    ];
    const key = primaryKeyShapes(entity, context);
    if (key.length > 0) {
        blocks.push(
            renderStruct(
                `${entity.name}PrimaryKey`,
                "The key a delete addresses, and a rows watch carries.",
                '#[serde(rename_all = "camelCase", deny_unknown_fields)]',
                key,
                context,
            ),
        );
    }
    return blocks;
}

/** The aliases the generator writes: concrete aliases in an entity file or a file marked `@primitive`. */
function generatedAliases(spec: SpecModel): Map<string, SpecTypeAlias> {
    const entityFiles = new Set([...spec.interfaces.values()].map((entity) => entity.filePath));
    const aliases = new Map<string, SpecTypeAlias>();
    for (const alias of spec.aliases.values()) {
        if (alias.typeParameters.length > 0) {
            continue;
        }
        if (alias.tags.primitive || entityFiles.has(alias.filePath)) {
            aliases.set(alias.name, alias);
        }
    }
    return aliases;
}

/** Group the aliases and entities the generator writes by their spec source file. */
function collectFileItems(spec: SpecModel, aliases: ReadonlyMap<string, SpecTypeAlias>): Map<string, FileItems> {
    const items = new Map<string, FileItems>();
    const ensure = (filePath: string): FileItems => {
        let entry = items.get(filePath);
        if (entry === undefined) {
            entry = { aliases: [], entities: [] };
            items.set(filePath, entry);
        }
        return entry;
    };

    for (const alias of aliases.values()) {
        ensure(alias.filePath).aliases.push(alias);
    }
    for (const entity of spec.interfaces.values()) {
        ensure(entity.filePath).entities.push(entity);
    }
    return items;
}

/** Render one generated source file: its header, imports, and items. */
function renderFile(itemBlocks: string[][], imports: Set<string>): string {
    const lines = [HEADER, ""];
    if (imports.size > 0) {
        lines.push(...[...imports].sort((a, b) => a.localeCompare(b)), "");
    }
    for (const block of itemBlocks) {
        lines.push(...block, "");
    }
    return `${lines.join("\n").trimEnd()}\n`;
}

/** Build every generated Rust file, keyed by its path relative to the output root. */
export function buildRustModels(spec: SpecModel): { files: GeneratedFiles; diagnostics: Diagnostic[] } {
    const aliases = generatedAliases(spec);
    const aliasNames = new Set(aliases.keys());
    const items = collectFileItems(spec, aliases);
    const files: GeneratedFiles = new Map();
    const diagnostics: Diagnostic[] = [];

    for (const [filePath, group] of [...items].sort(([a], [b]) => a.localeCompare(b))) {
        const context: RenderContext = {
            spec,
            generatedAliases: aliasNames,
            currentFilePath: filePath,
            imports: new Set(),
            diagnostics,
            usesPartial: false,
        };
        const blocks: string[][] = [];
        for (const alias of [...group.aliases].sort((a, b) => a.name.localeCompare(b.name))) {
            blocks.push(renderAlias(alias, context));
        }
        for (const entity of [...group.entities].sort((a, b) => a.name.localeCompare(b.name))) {
            blocks.push(...renderEntityStructs(entity, context));
        }
        if (context.usesPartial) {
            context.imports.add("use crate::Partial;");
        }
        files.set(outputPath(filePath), renderFile(blocks, context.imports));
    }

    for (const [path, content] of renderModuleTree(files)) {
        files.set(path, content);
    }

    return { files, diagnostics };
}

/** Build the `mod.rs` declarations for every generated directory. */
function renderModuleTree(files: ReadonlyMap<string, string>): GeneratedFiles {
    const root: ModuleTree = { dirs: new Map(), files: new Map() };
    const directories = new Map<string, ModuleTree>([["", root]]);

    const ensure = (path: string): ModuleTree => {
        let tree = directories.get(path);
        if (tree === undefined) {
            tree = { dirs: new Map(), files: new Map() };
            directories.set(path, tree);
        }
        return tree;
    };

    for (const relative of files.keys()) {
        const parts = relative.split("/");
        const module = parts.pop()?.replace(/\.rs$/u, "");
        if (module === undefined) {
            continue;
        }
        let path = "";
        let parent = root;
        for (const rawName of parts) {
            const childPath = path === "" ? rawName : `${path}/${rawName}`;
            const child = ensure(childPath);
            parent.dirs.set(rawName, { rawName, module: directoryModule(rawName) });
            parent = child;
            path = childPath;
        }
        parent.files.set(module, module);
    }

    const tree: GeneratedFiles = new Map();
    for (const [path, moduleTree] of directories) {
        if (moduleTree.dirs.size === 0 && moduleTree.files.size === 0) {
            continue;
        }
        const lines = [HEADER, ""];
        for (const entry of [...moduleTree.dirs.values()].sort((a, b) => a.module.localeCompare(b.module))) {
            lines.push(entry.rawName === entry.module ? `pub mod ${entry.module};` : `#[path = "${entry.rawName}/mod.rs"] pub mod ${entry.module};`);
        }
        for (const module of [...moduleTree.files.keys()].sort((a, b) => a.localeCompare(b))) {
            lines.push(`pub mod ${module};`);
        }
        tree.set(path === "" ? "mod.rs" : `${path}/mod.rs`, `${lines.join("\n").trimEnd()}\n`);
    }
    return tree;
}

/** List every generated `.rs` file under the output root, relative to it. */
function existingRustFiles(root: string): string[] {
    if (!existsSync(root)) {
        return [];
    }
    const found: string[] = [];
    const walk = (directory: string): void => {
        for (const entry of readdirSync(directory, { withFileTypes: true })) {
            const absolute = join(directory, entry.name);
            if (entry.isDirectory()) {
                walk(absolute);
            } else if (entry.name.endsWith(".rs")) {
                found.push(relativePath(root, absolute).split(/[\\/]/u).join("/"));
            }
        }
    };
    walk(root);
    return found;
}

/** Write the generated files, or with `--check`, report the ones that differ and write nothing. */
export function run(spec: SpecModel, argv: readonly string[] = process.argv, output: Output = console): number {
    const outIndex = argv.indexOf("--out");
    const outDir = outIndex === -1 ? DEFAULT_OUT_DIR : argv[outIndex + 1];
    if (!outDir) {
        output.error("--out needs a directory");
        return 1;
    }

    const { files, diagnostics } = buildRustModels(spec);
    for (const diagnostic of diagnostics) {
        output.error(`${diagnostic.filePath}:${diagnostic.line}: ${diagnostic.message}`);
    }
    if (diagnostics.length > 0) {
        return 1;
    }

    if (argv.includes("--check")) {
        const expected = new Set(files.keys());
        let drifted = 0;
        for (const [relative, content] of files) {
            const absolute = join(outDir, relative);
            if (!existsSync(absolute) || readFileSync(absolute, "utf8") !== content) {
                output.error(`out of date: ${relative}`);
                drifted++;
            }
        }
        for (const relative of existingRustFiles(outDir)) {
            if (!expected.has(relative)) {
                output.error(`stale: ${relative}`);
                drifted++;
            }
        }
        if (drifted > 0) {
            return 1;
        }
        output.log(`${files.size} model file(s) are up to date in ${outDir}`);
        return 0;
    }

    rmSync(outDir, { recursive: true, force: true });
    for (const [relative, content] of files) {
        const absolute = join(outDir, relative);
        mkdirSync(dirname(absolute), { recursive: true });
        writeFileSync(absolute, content);
    }
    output.log(`wrote ${files.size} model file(s) to ${outDir}`);
    return 0;
}

if (import.meta.main) {
    process.exitCode = run(loadSpec(), process.argv);
}
