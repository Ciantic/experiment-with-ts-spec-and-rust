/** Generate the per-entity filter types the read, its route guard, and its client share. See docs/queries.md. */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { SDK_PACKAGE_ROOT } from "../paths.ts";
import {
    declaredTypeOf,
    loadSpec,
    operatorArity,
    type QueryOperator,
    type SpecInterface,
    type SpecModel,
} from "../spec/spec-model.ts";

/** The channels a run reports on: the console, or a caller's own sink. */
type Output = Pick<Console, "log" | "error">;

/** Where the generated module is written when no `--out` is given. */
const DEFAULT_OUT_FILE = join(SDK_PACKAGE_ROOT, "src/filters.ts");

const HEADER = "// Generated by scripts/sdk/generate-filters.ts. Do not edit.";

/** The characters that separate a column from its operator in a flat filter key. */
export const FILTER_SEPARATOR = "__";

/** One filterable column: its name, the operators its `@queryFilter ops=` names, and the TS type of a value. */
export interface FilterColumn {
    name: string;
    operators: QueryOperator[];
    /** The value type as the spec writes it, e.g. `InvoiceId`, `Date`, or `string`. */
    valueType: string;
    /** The module `valueType` comes from; absent for a keyword or a built-in such as `Date`. */
    importSpecifier?: string;
}

/** One entity's filter type: its name and the columns it names. */
export interface EntityFilter {
    entity: string;
    typeName: string;
    columns: FilterColumn[];
}

/** `Invoice` -> `InvoiceFilter`. */
export function filterTypeName(entity: string): string {
    return `${entity}Filter`;
}

/** The filterable columns of an interface, in declaration order, as its tag names them. */
export function filterColumns(entity: SpecInterface, spec: SpecModel): FilterColumn[] {
    const columns: FilterColumn[] = [];
    for (const property of entity.properties) {
        const filter = property.tags.queryFilter;
        if (filter === undefined) {
            continue;
        }
        const declared = declaredTypeOf(spec, property.type);
        columns.push({
            name: property.name,
            operators: filter.ops,
            // A type the resolver cannot name is written as the spec spells it, with no import to add.
            valueType: declared?.name ?? property.typeText,
            ...(declared?.importSpecifier === undefined ? {} : { importSpecifier: declared.importSpecifier }),
        });
    }
    return columns;
}

/** One entry per entity that declares a read, in name order, so the generated module is stable. */
export function buildFilterModel(spec: SpecModel): EntityFilter[] {
    const entries: EntityFilter[] = [];
    for (const entity of spec.interfaces.values()) {
        // A read is what names a filter, so an entity without one has no type to share.
        if (!entity.queries.includes("query") && !entity.restQueries.includes("query")) {
            continue;
        }
        const columns = filterColumns(entity, spec);
        if (columns.length === 0) {
            continue;
        }
        entries.push({ entity: entity.name, typeName: filterTypeName(entity.name), columns });
    }
    entries.sort((a, b) => a.entity.localeCompare(b.entity));
    return entries;
}

/** The TS type of one comparison's value: the column's own, wrapped when the operator takes a list or a pair. */
export function operatorValueType(operator: QueryOperator, valueType: string): string {
    switch (operatorArity(operator)) {
        case 0:
            return "true";
        case 2:
            return `readonly [${valueType}, ${valueType}]`;
        case "list":
            return `readonly ${valueType}[]`;
        default:
            return valueType;
    }
}

/** The key one comparison is written as: `tenantId__eq`. */
export function comparisonKey(column: string, operator: QueryOperator): string {
    return `${column}${FILTER_SEPARATOR}${operator}`;
}

/** Render one entity's filter type as a union of single-key entries, one per column and operator. */
function renderEntityFilter(entry: EntityFilter): string[] {
    const members: string[] = [];
    for (const column of entry.columns) {
        for (const operator of column.operators) {
            const key = comparisonKey(column.name, operator);
            members.push(`    | { ${JSON.stringify(key)}: ${operatorValueType(operator, column.valueType)} }`);
        }
    }
    const [first, ...rest] = members;
    return [
        `/** One comparison a filter over \`${entry.entity}\` may name, as a flat \`column${FILTER_SEPARATOR}operator\` entry. */`,
        `export type ${entry.typeName} =`,
        first?.replace(/^ {4}\| /, "    ") ?? "    never",
        ...rest,
        ...(members.length === 0 ? [] : []),
    ].map((line, index, all) => (index === all.length - 1 ? `${line};` : line));
}

/** The `import type` lines one entity's filter needs, sorted so the module is stable. */
function importLines(entry: EntityFilter): string[] {
    const imports = new Set<string>();
    for (const column of entry.columns) {
        if (column.importSpecifier !== undefined) {
            imports.add(`import type { ${column.valueType} } from "${column.importSpecifier}";`);
        }
    }
    return [...imports].sort();
}

/** Render the module: one filter type per entity, each the union a read's `filters` take. */
export function renderFiltersModule(entries: EntityFilter[]): string {
    const lines: string[] = [HEADER];
    const imports = new Set(entries.flatMap(importLines));
    if (imports.size > 0) {
        lines.push(...[...imports].sort());
        lines.push("");
    }
    for (const entry of entries) {
        lines.push(...renderEntityFilter(entry));
        lines.push("");
    }
    return lines.join("\n");
}

/** Write the module for a parsed spec and return the exit code. */
export function run(spec: SpecModel, argv: readonly string[] = process.argv, output: Output = console): number {
    const outIndex = argv.indexOf("--out");
    const outFile = outIndex === -1 ? DEFAULT_OUT_FILE : argv[outIndex + 1];
    if (!outFile) {
        output.error("--out needs a file");
        return 1;
    }

    const entries = buildFilterModel(spec);
    mkdirSync(dirname(outFile), { recursive: true });
    writeFileSync(outFile, renderFiltersModule(entries));
    output.log(`wrote ${entries.length} filter type(s) to ${outFile}`);
    return 0;
}

if (import.meta.main) {
    process.exitCode = run(loadSpec(), process.argv);
}
