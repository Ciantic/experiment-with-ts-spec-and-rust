/** Generate the per-entity filter maps the read types and the guard modules share. See docs/queries.md. */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { SDK_PACKAGE_ROOT } from "../paths.ts";
import { loadSpec, type SpecInterface, type SpecModel } from "../spec/spec-model.ts";

/** The channels a run reports on: the console, or a caller's own sink. */
type Output = Pick<Console, "log" | "error">;

/** Where the generated module is written when no `--out` is given. */
const DEFAULT_OUT_FILE = join(SDK_PACKAGE_ROOT, "src/filters.ts");

const HEADER = "// Generated by scripts/sdk/generate-filters.ts. Do not edit.";

/** One filterable column: its name and the operators its `@queryFilter ops=` names. */
export interface FilterColumn {
    name: string;
    operators: string[];
}

/** One entity's filter map: its name, the type that carries it, and the columns it names. */
export interface EntityFilter {
    entity: string;
    typeName: string;
    columns: FilterColumn[];
}

/** `Invoice` -> `InvoiceFilter`. */
export function filterTypeName(entity: string): string {
    return `${entity}Filter`;
}

/** The filterable columns of an interface, in declaration order, as its tag names them. */
export function filterColumns(entity: SpecInterface): FilterColumn[] {
    const columns: FilterColumn[] = [];
    for (const property of entity.properties) {
        const filter = property.tags.queryFilter;
        if (filter !== undefined) {
            columns.push({ name: property.name, operators: filter.ops });
        }
    }
    return columns;
}

/** One entry per entity that declares a read, in name order, so the generated module is stable. */
export function buildFilterModel(spec: SpecModel): EntityFilter[] {
    const entries: EntityFilter[] = [];
    for (const entity of spec.interfaces.values()) {
        // A read is what names a filter, so an entity without one has no map to share.
        if (!entity.queries.includes("query") && !entity.restQueries.includes("query")) {
            continue;
        }
        const columns = filterColumns(entity);
        if (columns.length === 0) {
            continue;
        }
        entries.push({ entity: entity.name, typeName: filterTypeName(entity.name), columns });
    }
    entries.sort((a, b) => a.entity.localeCompare(b.entity));
    return entries;
}

/** A property key, quoted only when it is not a plain identifier. */
function propertyKey(name: string): string {
    return /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
}

/** One column's line: its name, then the operators as a union of string literals. */
function renderColumn(column: FilterColumn): string {
    const operators = column.operators.map((operator) => JSON.stringify(operator)).join(" | ");
    return `    ${propertyKey(column.name)}: ${operators};`;
}

/** Render the module: one operator map per entity, each the object `Filter<Entity, …>` takes. */
export function renderFiltersModule(entries: EntityFilter[]): string {
    const lines: string[] = [HEADER];
    for (const entry of entries) {
        lines.push("");
        lines.push(
            `/** The comparisons a filter over \`${entry.entity}\` may name, one entry per \`@queryFilter\` column. */`,
        );
        lines.push(`export type ${entry.typeName} = {`);
        for (const column of entry.columns) {
            lines.push(renderColumn(column));
        }
        lines.push("};");
    }
    lines.push("");
    return lines.join("\n");
}

/** Write the module for a parsed spec and return the exit code. */
export function run(spec: SpecModel, argv: readonly string[] = process.argv, output: Output = console): number {
    const outIndex = argv.indexOf("--out");
    const outFile = outIndex === -1 ? DEFAULT_OUT_FILE : argv[outIndex + 1];
    if (!outFile) {
        output.error("--out needs a file");
        return 1;
    }

    const entries = buildFilterModel(spec);
    mkdirSync(dirname(outFile), { recursive: true });
    writeFileSync(outFile, renderFiltersModule(entries));
    output.log(`wrote ${entries.length} filter map(s) to ${outFile}`);
    return 0;
}

if (import.meta.main) {
    process.exitCode = run(loadSpec(), process.argv);
}
